def courses(y0, y1, n, depth, z0=-4.0, z1=4.0, seam=0.08, ch=0.03):
	# n horizontal board courses between y0 and y1 with `seam` gaps (the wall behind shows as a dark groove).
	h = (y1 - y0 - seam * (n - 1)) / n
	out = []
	for i in range(n):
		a = y0 + i * (h + seam)
		out.append(rb(0, depth, a, a + h, z0, z1, ch=ch))
	return G(*out)


