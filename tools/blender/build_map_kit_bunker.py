def p_door_lining(mats, kit):
	# 8 x 10 opening through a 2-thick wall: steel lining (jambs, head, threshold), a frame on both faces and an
	# end-colour stripe on each frame head. Origin: opening centre on the floor, wall thickness along X.
	# A box-out frame: the lining plates run 0.45 past both wall faces (proud of the 0.3 cladding, whose ends they
	# hide) and stay inside the opening, so a door beside a corner never cuts into the next wall.
	lining = G(
		rb(-1.45, 1.45, 0, 0.05, -4, 4),  # sill plate (the jambs stand on it)
		rb(-1.45, 1.45, 0.05, 9.6, -4, -3.85),
		rb(-1.45, 1.45, 0.05, 9.6, 3.85, 4),
		rb(-1.45, 1.45, 9.6, 10.0, -4, 4),  # head (over the jamb tops)
	)
	trim = [rb(s * 1.45, s * 1.51, 9.65, 9.95, -3.8, 3.8) for s in (1, -1)]
	# A sign plate on the lintel over each face (Art.luau writes the room beyond, or removes it under a deck).
	piece("DoorLining", {
		"Lining": (lining, "M_Steel"), "Trim": (G(*trim), "M_Trim"),
		"SignP": (rb(1.0, 1.1, 10.6, 11.8, -3.0, 3.0, ch=0.02), "M_Sign"),
		"SignM": (rb(-1.1, -1.0, 10.6, 11.8, -3.0, 3.0, ch=0.02), "M_Sign"),
	}, mats, kit)


def p_blast_door(mats, kit):
	# The gallery's jammed blast door: a 16 x 12 opening (z -8..8) through the 2-thick back wall, a chunky frame on both
	# faces, the east leaf (z 0..7.85) stuck shut in the wall plane, hazard chevrons on its leading edge.
	# Opening z -7..7 (passage -7..1, leaf 1..6.85). The gallery face (+X) gets the chunky frame with a head (the
	# gallery is 26 tall); the vestibule face (-X) only box-out lips (its ceiling is at the opening's top, 12).
	lining = G(
		rb(-1.45, 1, 0, 0.05, -7, 7),
		rb(-1.45, 1, 0.05, 11.85, -7, -6.85),
		rb(-1.45, 1, 0.05, 11.85, 6.85, 7),
		rb(-1.45, 1, 11.85, 12.0, -7, 7),
	)
	frame = [
		rb(1.32, 1.92, 0, 12.0, -8.4, -6.85, ch=0.06),
		rb(1.32, 1.92, 0, 12.0, 6.85, 8.4, ch=0.06),
		rb(1.32, 1.92, 12.0, 13.4, -8.4, 8.4, ch=0.06),
	]
	trim = [rb(1.92, 1.98, 12.45, 12.95, -7.2, 7.2)]
	bolts = []
	for zc in (-7.62, 7.62):
		for k in range(7):
			y = 1.0 + k * 1.6
			bolts.append(xcyl(y, zc, 0.16, 1.92, 2.0, segs=6))
	leaf = [rb(-0.5, 0.5, 0.05, 11.85, 1.0, 6.85, ch=0.04)]
	for s in (1, -1):
		for y in (2.0, 5.0, 8.0, 10.6):
			leaf.append(rb(s * 0.5, s * 0.62, y, y + 0.35, 2.0, 6.4, ch=0.02))
	hz_base, hz_stripe = [], []
	for s in (1, -1):
		hz_base.append(rb(s * 0.5, s * 0.56, 0.05, 11.85, 1.05, 1.9))
		y = 0.25
		while y + 0.45 < 11.75:
			hz_stripe.append(rb(s * 0.56, s * 0.61, y, y + 0.4, 1.12, 1.83))
			y += 0.8
	piece("BlastDoor", {
		"Lining": (lining, "M_Steel"),
		"Frame": (G(*frame, *bolts), "M_Steel"),
		"Trim": (G(*trim), "M_Trim"),
		"Leaf": (G(*leaf), "M_Door"),
		"HazardBase": (G(*hz_base), "M_Black"),
		"HazardStripe": (G(*hz_stripe), "M_Hazard"),
	}, mats, kit)


