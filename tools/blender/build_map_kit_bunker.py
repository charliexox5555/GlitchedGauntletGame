def p_shaft(mats, kit):
	# Shaft lining: a steel knife-edge rim at the ceiling opening with a warm cove on it, then board-formed courses
	# with tie holes up to the skylight. The grazing sun shows the courses (Bruder Klaus).
	n = 11
	seam = 0.08
	h = (38.0 - 0.6 - seam * (n - 1)) / n
	ties = []
	for i in range(n):
		yc = 0.6 + i * (h + seam) + h / 2
		for zc in (-2.0, 2.0):
			ties.append(xcyl(yc, zc, 0.11, 0.15, 0.21, segs=8))
	p = {
		"Rim": (rb(0, 0.3, 0, 0.6, -4, 4, ch=0.02), "M_Steel"),
		"Rim_Glow": (rb(0.16, 0.28, 0.6, 0.66, -3.9, 3.9), "G_Cove"),
		"Field": (courses(0.6, 38.0, n, 0.15), "M_BoardLight"),
		"Ties": (G(*ties), "M_Tie"),
	}
	piece("ShaftPanel8", p, mats, kit)
	# Skylight: a steel curb on the shaft walls (pinwheel, butt joints), glazing bars at two depths (x-bars deeper
	# than z-bars, so the crossings share no plane) and one glass sheet between.
	curb = G(
		rb(-14, 12, 0, 0.8, 12, 14), rb(12, 14, 0, 0.8, -12, 14),
		rb(-12, 14, 0, 0.8, -14, -12), rb(-14, -12, 0, 0.8, -14, 12),
	)
	bars = []
	for c in (-6.0, 0.0, 6.0):
		bars.append(rb(-12, 12, 0.1, 0.7, c - 0.12, c + 0.12))
		bars.append(rb(c - 0.12, c + 0.12, 0.2, 0.6, -12, 12))
	p = {
		"Curb": (curb, "M_Steel"),
		"Bars": (G(*bars), "M_Steel"),
		"Glass": (rb(-11.95, 11.95, 0.35, 0.45, -11.95, 11.95), "M_Glass"),
	}
	piece("ShaftTop", p, mats, kit)


def p_sun(mats, kit):
	# The sun dais: a honed stone square with a brass compass (ring + four points) around the plinth.
	pts = []
	for k in range(4):
		a = math.radians(90 * k)
		ux, uz = math.cos(a), math.sin(a)
		vx, vz = -uz, ux
		tip = (ux * 7.6, uz * 7.6)
		b1 = (ux * 4.2 + vx * 0.35, uz * 4.2 + vz * 0.35)
		b2 = (ux * 4.2 - vx * 0.35, uz * 4.2 - vz * 0.35)
		pts.append(ry([b1, tip, b2], 0.5, 0.55))
	# The ring stops short of the points (four arcs), so no two brass parts overlap in the inlay's plane.
	arcs = []
	for k in range(4):
		a = K.arc(6.3, 6.6, 90 * k + 9.0, 90 * k + 81.0, 0.5, 0.55, steps=12)
		arcs.append(K.mat_all(a, 0))
	p = {
		"Slab": (rb(-8, 8, 0, 0.5, -8, 8, ch=0.06), "M_Dais"),
		"Compass": (G(*arcs, *pts), "M_Brass"),
	}
	piece("SunDais", p, mats, kit)
	# The sun plinth: an 8 x 8 board-formed monolith on the dais (courses proud of a dark core, so the joints read),
	# tie holes, a brass cap and a brass gnomon fin catching the sun.
	cs = []
	ys = [(0.5, 3.1), (3.18, 5.78), (5.86, 8.5)]
	for a, b in ys:
		cs.append(rb(-4, 4, a, b, -4, 4, ch=0.05))
	ties = []
	for a, b in ys:
		yc = (a + b) / 2
		for t in (-2.0, 2.0):
			ties.append(xcyl(yc, t, 0.12, 4.0, 4.06, segs=8))
			ties.append(xcyl(yc, t, 0.12, -4.06, -4.0, segs=8))
			ties.append(zcyl(t, yc, 0.12, 4.0, 4.06, segs=8))
			ties.append(zcyl(t, yc, 0.12, -4.06, -4.0, segs=8))
	p = {
		"Core": (rb(-3.9, 3.9, 0.6, 8.4, -3.9, 3.9), "M_Skirt"),
		"Courses": (G(*cs), "M_BoardLight"),
		"Ties": (G(*ties), "M_Tie"),
		"Cap": (rb(-3.6, 3.6, 8.5, 8.6, -3.6, 3.6, ch=0.02), "M_Brass"),
		"Gnomon": (rx([(-2.6, 8.6), (2.6, 8.6), (-2.6, 10.6)], -0.08, 0.08), "M_Brass"),
	}
	piece("SunPlinth", p, mats, kit)


