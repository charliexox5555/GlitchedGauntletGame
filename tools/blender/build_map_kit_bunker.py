# build_map_kit_bunker.py: the Bunker map kit, group "Bunker" (vault/01 Design/Maps/Bunker.md, "How a map is built" in
# vault/01 Design/Maps/00 Maps.md). The Sunwell Bunker's lower levels in the Lobby's materials: board-formed concrete
# cladding with a painted lower wall and an end-colour line, steel-lined doors, the jammed blast doors, the light
# shaft lining and skylight, the sun dais and plinth, the ring's edge and rails, beams and pilasters, the gallery
# stairs, and the story props (lockers, racks, consoles, generators, pump cabinets, manifolds, crates), lights,
# pipes and signs.
#
# Every piece is a collection Map_<Piece> built at the world origin, modelled in ROBLOX MAP SPACE terms (rb/rx/rz/ry
# convert): +X across, +Y up, +Z along; Blender = (x, -z, y), the importer's own mapping, so put(piece, at(x, y, z,
# yaw)) in Art.luau lands them exactly. Origins (placements are generated by tools/maps/bunker_art.py):
#   wall pieces (Clad12, Clad10, Field14, Pilaster14, Corbel, SignPlate, SpawnPanel, WallLamp, PipeRun8, Lockers4,
#     Rack4, PumpUnit, Manifold, CrateStack, CrateRow): on the floor at the wall face, facing +X (into the room),
#     length along Z (8 long pieces span z -4..4 and are stretched along Z to their run). Field14, Pilaster14 and
#     Corbel are placed at y 12 (Field14, Pilaster14) or 24.5 (Corbel).
#   CornerPost12: at a convex wall corner on the floor; the post fills the quadrant x 0..0.42, z 0..0.42.
#   DoorLining (8 x 10 opening through a 2-thick wall) and BlastDoor (16 x 12): at the opening's centre on the floor,
#     mid-thickness; the wall thickness runs along X (x -1..1), the opening along Z.
#   ShaftPanel8: at the shaft wall's inner face, y 0 = the sunwell ceiling (26), up to the skylight (64).
#   ShaftTop: the shaft's centre at the skylight level (64). SunDais, SunPlinth: the map centre on the floor.
#   Beam8: the ceiling plane (y 0 = 26), hanging down 1.5, along Z. RingEdge8: on the deck's inner edge plane, facing
#     +X (into the void), heights absolute. Rail8: on a parapet's top centreline (y 0 = 15), along Z.
#   GalleryStair: the bottom of the flight at its centre; it rises toward -Z (18 run, 12 rise), x -3..3.
#   LinearLight, CageLamp: the ceiling plane (y 0 = 12), hanging down. Props on the floor at their centre.
# Parts named *_Band / *_Trim take the end colour in Studio (Art.luau). Neon parts are separate *_Glow objects.
#
# NO Z-FIGHTING (the user's rule): within a piece, parts butt edge to edge (never overlap in a shared plane), trims,
# bands, stripes and sign plates stand >= 0.05 proud, crossing members sit at different depths. After building, the
# script exports every axis-aligned face rectangle of every part (art-source/maps/Bunker/Exports/Bunker_faces.json),
# which tools/maps/bunker_art.py checks on the fully dressed map, and runs the same check inside each piece here.
