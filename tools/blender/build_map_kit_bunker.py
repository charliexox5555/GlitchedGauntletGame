# ---------------------------------------------------------------- face export + the in-piece coplanar check

def b2r(v):
	return (v[0], v[2], -v[1])


def face_rects(ob):
	# Axis-aligned planar faces of each mesh island, in Roblox piece-local coords: [(ax, sign, plane, (u0,u1), (v0,v1))]
	me = ob.data
	bm = bmesh.new()
	bm.from_mesh(me)
	bm.faces.ensure_lookup_table()
	# islands
	island = {}
	idx = 0
	for f in bm.faces:
		if f.index in island:
			continue
		stack = [f]
		while stack:
			g = stack.pop()
			if g.index in island:
				continue
			island[g.index] = idx
			for e in g.edges:
				for h in e.link_faces:
					if h.index not in island:
						stack.append(h)
		idx += 1
	# Coplanar patches: axis-aligned faces with the same plane and facing, joined only across shared edges (so two
	# separate faces in one plane, e.g. a lining's two jamb bottoms, stay two rectangles).
	fkey = {}
	for f in bm.faces:
		n = f.normal
		rn = (n.x, n.z, -n.y)
		ax = max(range(3), key=lambda k: abs(rn[k]))
		if abs(rn[ax]) < 0.9995:
			continue
		pts = [b2r(v.co) for v in f.verts]
		fkey[f.index] = (ax, 1 if rn[ax] > 0 else -1, round(sum(p[ax] for p in pts) / len(pts), 4))
	patch = {}
	pid = 0
	for f in bm.faces:
		if f.index not in fkey or f.index in patch:
			continue
		stack = [f]
		while stack:
			g = stack.pop()
			if g.index in patch:
				continue
			patch[g.index] = pid
			for e in g.edges:
				for h in e.link_faces:
					if h.index not in patch and fkey.get(h.index) == fkey[f.index]:
						stack.append(h)
		pid += 1
	# A patch that isn't a filled rectangle (an arc, a triangle) is exported face by face, so its bounding box never
	# claims area the surface doesn't cover.
	area, box2 = {}, {}
	for f in bm.faces:
		if f.index in fkey:
			ax = fkey[f.index][0]
			o = [k for k in range(3) if k != ax]
			pts = [b2r(v.co) for v in f.verts]
			area[patch[f.index]] = area.get(patch[f.index], 0.0) + f.calc_area()
			b = box2.setdefault(patch[f.index], [math.inf, -math.inf, math.inf, -math.inf])
			for p in pts:
				b[0], b[1] = min(b[0], p[o[0]]), max(b[1], p[o[0]])
				b[2], b[3] = min(b[2], p[o[1]]), max(b[3], p[o[1]])
	rect = {k: area[k] >= 0.98 * (b[1] - b[0]) * (b[3] - b[2]) for k, b in box2.items()}
	groups = {}
	for f in bm.faces:
		if f.index not in fkey:
			continue
		ax, sign, plane = fkey[f.index]
		pts = [b2r(v.co) for v in f.verts]
		key = (patch[f.index], -1 if rect[patch[f.index]] else f.index, ax, sign, plane)
		o = [k for k in range(3) if k != ax]
		g = groups.setdefault(key, [math.inf, -math.inf, math.inf, -math.inf])
		for p in pts:
			g[0] = min(g[0], p[o[0]])
			g[1] = max(g[1], p[o[0]])
			g[2] = min(g[2], p[o[1]])
			g[3] = max(g[3], p[o[1]])
	bm.free()
	out = []
	for (isl, _sub, ax, sign, plane), g in groups.items():
		out.append((isl, ax, sign, plane, (round(g[0], 4), round(g[1], 4)), (round(g[2], 4), round(g[3], 4))))
	return out


def piece_check(name, rects_by_obj):
	# Same-facing coplanar overlaps inside one piece (between parts, and between islands of one part).
	items = []
	for oname, rects in rects_by_obj.items():
		for isl, ax, sign, plane, ur, vr in rects:
			items.append((oname, isl, ax, sign, plane, ur, vr))
	bad = []
	for i in range(len(items)):
		a = items[i]
		for j in range(i + 1, len(items)):
			b = items[j]
			if a[0] == b[0] and a[1] == b[1]:
				continue
			if a[2] != b[2] or a[3] != b[3] or abs(a[4] - b[4]) >= 0.02:
				continue
			u0, u1 = max(a[5][0], b[5][0]), min(a[5][1], b[5][1])
			v0, v1 = max(a[6][0], b[6][0]), min(a[6][1], b[6][1])
			if u1 - u0 >= 0.05 and v1 - v0 >= 0.05:
				bad.append((a[0], b[0], "xyz"[a[2]], a[3], round(a[4], 3), round((u1 - u0) * (v1 - v0), 3)))
	return bad


def export_faces():
	data = {"note": "axis-aligned face rectangles per kit part, Roblox piece-local (x, y up, z); per entry: "
					"[axis 0/1/2, sign, plane, [u0, u1], [v0, v1]] on the two other axes in order",
			"pieces": {}}
	problems = {}
	for name, col in PIECES:
		by_obj = {}
		for ob in col.all_objects:
			if ob.type != "MESH" or ob.get("preview_only"):
				continue
			by_obj[ob.name] = face_rects(ob)
		bad = piece_check(name, by_obj)
		if bad:
			problems[name] = bad
		data["pieces"][name] = {o: [[ax, s, p, list(u), list(v)] for _, ax, s, p, u, v in r] for o, r in by_obj.items()}
	os.makedirs(os.path.dirname(FACES_OUT), exist_ok=True)
	with open(FACES_OUT, "w") as f:
		json.dump(data, f)
	n = sum(len(v) for v in problems.values())
	print("BUNKER_PIECE_COPLANAR %d" % n)
