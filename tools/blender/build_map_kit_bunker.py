def samples(default):
	return int(ARGS[ARGS.index("--samples") + 1]) if "--samples" in ARGS else default


def sheet(mats, tris):
	sc = bpy.context.scene
	stage = K.collection("Sheet")
	cell = 30.0
	ncol = 7
	order = sorted(PIECES, key=lambda t: t[0])
	nrow = (len(order) + ncol - 1) // ncol
	fl = K.add_obj("SheetFloor", K.cbox(-cell * (nrow - 0.4), cell * 0.6, -cell * 0.6, cell * (ncol - 0.4), -0.2, 0, ch=0), [mats["ConcreteHoned"]], stage)
	fl["preview_only"] = True
	for idx, (name, col) in enumerate(order):
		r, c = divmod(idx, ncol)
		lo = Vector((1e9, 1e9, 1e9))
		hi = -lo
		for ob in col.all_objects:
			if ob.type != "MESH":
				continue
			for v in ob.data.vertices:
				for i in range(3):
					lo[i] = min(lo[i], v.co[i])
					hi[i] = max(hi[i], v.co[i])
		size = hi - lo
		s = min(2.5, 22.0 / max(size.x, size.y, size.z, 0.01))
		ctr = (lo + hi) / 2
		px, py = -r * cell, c * cell
		m = Matrix.Translation((px, py, 0)) @ Matrix.Scale(s, 4) @ Matrix.Translation((-ctr.x, -ctr.y, -lo.z))
		e = bpy.data.objects.new("Sheet_" + name, None)
		e.instance_type = "COLLECTION"
		e.instance_collection = col
		e.matrix_world = m
		stage.objects.link(e)
		label = "%s  %d tris  %.1fx%.1fx%.1f%s" % (name, tris[name], size.x, size.z, size.y, "" if abs(s - 1) < 1e-3 else "  (x%.2f)" % s)
		K.text(label, 1.2, (px + 12.5, py, 0.05), stage, mats["SignText"], rot=(0, 0, 90), font=K.FONT_LABEL)
	sun = bpy.data.lights.new("SheetSun", "SUN")
	sun.energy = 3.2
	sun.angle = math.radians(3)
	so = bpy.data.objects.new("SheetSun", sun)
	stage.objects.link(so)
	so.rotation_euler = (math.radians(42), math.radians(-25), math.radians(200))
	w = sc.world or bpy.data.worlds.new("World")
	sc.world = w
	w.use_nodes = True
	bg = w.node_tree.nodes.get("Background")
	if bg:
		bg.inputs[0].default_value = (*K.lin(0x5A6272), 1)
		bg.inputs[1].default_value = 1.3
	cx, cy = -(nrow - 1) * cell / 2, (ncol - 1) * cell / 2
	cam = K.camera((cx + 260, cy + 60, 250), (cx, cy, 4), lens=50, name="SheetCam", col=stage)
	cam.data.type = "ORTHO"
	cam.data.ortho_scale = cell * ncol * 1.05
	K.render_settings(samples=samples(24))
	try:
		sc.eevee.use_raytracing = False
	except AttributeError:
		pass
	K.bloom(strength=0.35)
	return stage


def kit_col(name):
	return bpy.data.collections["Map_" + name]


def put(name, x, y, z, yaw_deg, sz, col):
	m = Matrix.Translation((x, -z, y)) @ Matrix.Rotation(math.radians(yaw_deg), 4, "Z") @ Matrix.Scale(sz, 4, (0, 1, 0))
	return K.place_instance(kit_col(name), m, "P_" + name, col)


FINISH = {"polished": "P_FloorSun", "honed": "P_Floor", "ring": "P_Deck"}


def greybox_material(b, mats):
	if b.kind == "floor":
		return mats[FINISH.get(b.art, "P_Floor")]
	if b.kind == "roof":
		return mats["P_Ceil"]
	if b.kind == "deck":
		return mats["P_Deck"]
	if b.kind == "low":
		return mats["P_Parapet"]
	return mats["P_Wall"]


def dress(mats, col, roofs=True):
	import bunker_layout as L
	import bunker_art as A
	A.build()
	tint_b = mats["M_Band"]
	for b in L.BLOCKS:
		if b.art == "hide" or b.kind == "glass":
			continue
		if not roofs and b.kind == "roof":
			continue
		ob = K.add_obj("GB_" + b.name, rb(b.x0, b.x1, b.y0, b.y1, b.z0, b.z1), [greybox_material(b, mats)], col)
		ob["preview_only"] = True
	for p in A.PLACES:
		if ("Map_" + p.piece) not in bpy.data.collections:
			print("missing piece", p.piece)
			continue
		put(p.piece, p.x, p.y, p.z, p.yaw, p.sz, col)
	return L, A


