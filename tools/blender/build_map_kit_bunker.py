def stone_material(name, color, rbx="Concrete", speck=0.06):
	m, g, b = K._base(name, rbx, "", color)
	u, v = g.uv()
	p = g.xyz(u, v, 0.0)
	cloud = g.remap(g.noise(p, 0.2, 3.0), 0.3, 0.7, 0.93, 1.05)
	vo = g.voronoi(p, 4.0)
	sp = g.mul(g.inv(g.smooth(0.1, 0.18, vo.outputs["Distance"])), g.smooth(0.5, 0.55, g.sep(vo.outputs["Color"])[0]))
	f = g.mul(cloud, g.add(1.0, g.mul(sp, -speck)))
	g.set(b.inputs["Base Color"], g.col(color, f))
	g.set(b.inputs["Roughness"], g.remap(g.noise(p, 0.5, 2.0), 0.3, 0.7, 0.62, 0.8))
	return m


