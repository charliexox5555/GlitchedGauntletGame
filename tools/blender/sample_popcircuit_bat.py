
"""Sample the authored Bat poses for the in-game Blender camera-space rig."""
from pathlib import Path
import sys

from mathutils import Matrix

sys.path.insert(0,str(Path(__file__).resolve().parent))
from popcircuit_bat_motion import CATCH, CONTACT, FPS, GRIP, KEYS, RELEASE, TRAIL, pose

root = Path(__file__).resolve().parents[2]
dest = root/"src/client/Util/PopCircuitBatPoses.luau"
axes = Matrix(((0,-1,0),(0,0,1),(-1,0,0)))
inverse = axes.inverted()
lines = ["--!strict", "-- Generated by tools/blender/sample_popcircuit_bat.py.",
         "return {", f"	fps = {FPS},", f"	trailStart = {TRAIL[0]},", f"	trailEnd = {TRAIL[1]},",
         f"	release = {RELEASE},", f"	catch = {CATCH},",
         f"	grip = {GRIP.x:.2f},",
         "	contact = { "+", ".join(f"{k} = {v}" for k,v in CONTACT.items())+" },"]

def values(seq):
    return ", ".join(str(round(float(v),5)) for v in seq)

for name, keys in KEYS.items():
    lines.append(f"	{name} = {{")
    for frame in range(1,max(keys)+1):
        origin,rot,palm,left,_,support = pose(name,frame)
        q = (axes @ rot.to_matrix() @ inverse).to_quaternion()
        lines.append("		{ "+values((*(axes@origin),q.x,q.y,q.z,q.w,*(axes@palm),*(axes@left),support))+" },")
    lines.append("	},")
lines.append("}")
dest.write_text("\n".join(lines)+"\n",encoding="utf-8")
print("BAT_POSES",dest)

