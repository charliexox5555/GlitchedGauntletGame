"""Generate src/shared/WeaponAnimations/<Id>.luau from the Blender exports.

    python tools/make_weapon_anims.py

Each module holds the Fire and Reload clips sampled once per frame from the
gun's NLA strips (see tools/blender/export_weapons.py). Per bone the frames are
a flat array of 7 numbers per frame: x, y, z, qw, qx, qy, qz, the bone's local
transform relative to rest. That maps 1:1 onto the gun's Motor6D.Transform
because WeaponBuilder builds each joint in the bone's own axes.
The Flash bone only scales (a Blender preview of the flash), so it is skipped.
"""

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
EXPORTS = os.path.join(ROOT, "art-source", "weapons", "Exports")
OUT = os.path.join(ROOT, "src", "shared", "WeaponAnimations")
SKIP_BONES = {"Flash"}


def num(v):
	v = round(v, 3)
	if v == 0:
		return "0"
	s = f"{v:.3f}".rstrip("0").rstrip(".")
	return s.replace("0.", ".", 1) if s.startswith("0.") else s.replace("-0.", "-.", 1)


def clip_lua(clip, indent):
	frames = clip["end"] - clip["start"] + 1
	lines = [f"{indent}{{", f"{indent}\tframes = {frames},", f"{indent}\tbones = {{"]
	for bone, data in sorted(clip["bones"].items()):
		if bone in SKIP_BONES:
			continue
		flat = []
		for fr in data:
			flat.extend(num(v) for v in fr[:7])
		lines.append(f"{indent}\t\t{bone} = {{ {', '.join(flat)} }},")
	lines += [f"{indent}\t}},", f"{indent}}}"]
	return "\n".join(lines)


def main():
	os.makedirs(OUT, exist_ok=True)
	for name in sorted(os.listdir(EXPORTS)):
		if not name.endswith(".json") or name == "assets.json":
			continue
		data = json.load(open(os.path.join(EXPORTS, name)))
		gid = data["id"]
		anims = data.get("animations", {})
		fps = next(iter(anims.values()))["fps"] if anims else 24
		body = [
			"--!strict",
			f"-- Generated by tools/make_weapon_anims.py from art-source/weapons/Exports/{gid}.json.",
			"-- Do not edit by hand: change the animation in Blender and re-export.",
			"-- Per bone: x, y, z, qw, qx, qy, qz per frame (local transform from rest).",
			"",
			"return {",
			f"\tfps = {fps},",
		]
		for clip_name in ("Fire", "Reload"):
			if clip_name in anims:
				body.append(f"\t{clip_name} = " + clip_lua(anims[clip_name], "\t").lstrip() + ",")
		body.append("}")
		with open(os.path.join(OUT, gid + ".luau"), "w", newline="\n") as f:
			f.write("\n".join(body) + "\n")
	print("ok")


if __name__ == "__main__":
	main()
