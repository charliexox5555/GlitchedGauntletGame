#!/usr/bin/env python3
"""Greenhouse2 art pass (vault/01 Design/Maps/Greenhouse2.md): Greenhouse's placements (tools/maps/greenhouse_art.py,
on the kept layout) under the new map id and origin, with the Greenhouse2 kit, plus Greenhouse2's own decor.

    python tools/maps/greenhouse2_art.py    writes tools/studio/maps/Greenhouse2/Art.luau

The Greenhouse files are never written: this module patches greenhouse_art's output paths and template in memory.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import greenhouse_art as GA  # noqa: E402

ROOT = HERE.parents[1]
GA.ART_OUT = ROOT / "tools/studio/maps/Greenhouse2/Art.luau"
GA.PLAN_OUT = ROOT / "art-source/maps/Greenhouse2/plan.json"
GA.EXPORTS = ROOT / "art-source/maps/Greenhouse2/Exports"

GA.ART_TEMPLATE = (
    GA.ART_TEMPLATE.replace('newMap("Greenhouse", CFrame.new(1500, 200, -1500))', 'newMap("Greenhouse2", CFrame.new(0, 200, 3000))')
    .replace("-- Greenhouse art pass: GENERATED by tools/maps/greenhouse_layout.py --write (placements in tools/maps/greenhouse_art.py).",
             "-- Greenhouse2 art pass: GENERATED by tools/maps/greenhouse2_art.py (Greenhouse's placements on the kept layout,\n-- the Greenhouse2 kit, and Greenhouse2's own decor).")
    .replace("kit_bundle.py Greenhouse Structure -o gh_kit1.luau", "kit_bundle.py Greenhouse2 Structure -o gh2_kit1.luau")
    .replace("kit_bundle.py Greenhouse Garden -o gh_kit2.luau", "kit_bundle.py Greenhouse2 Garden -o gh2_kit2.luau")
    .replace("bundle.py Greenhouse Greybox Art Lighting -o greenhouse.luau", "bundle.py Greenhouse2 Greybox Art Lighting -o greenhouse2.luau")
    .replace('"Greenhouse art: %%d of %%d pieces placed', '"Greenhouse2 art: %%d of %%d pieces placed')
)

_build = GA.Art.build


def build(self):
    _build(self)
    # Greenhouse2 decor (concept 02-hero): banded flower tubs by the Dome's doors and the Fern House beds, at walls
    # and bed ends, never in a lane (no collision). Team B's half; both() adds A's turned copy.
    for x, z in DECOR_TUBS:
        self.both("Garden", "FlowerTub", x, 0, z, 0)
    return self


# map space (x, z), B half; measured clear of the collision on the layout plan
DECOR_TUBS: list[tuple[float, float]] = [
    (12.2, 38.0), (-0.2, 38.0),  # inside the Dome's north door, either side
    (38.0, 30.2), (38.0, 17.8),  # inside the Dome's east door
    (-22.0, 76.2), (-22.0, 63.8),  # Fern House, at its west door
    (22.0, 60.2), (22.0, 47.8),  # Fern House, at its east door
]  # from a clearance search on the layout blocks (1.5 radius, 3.0 off the wall plane, no solid below 4)

GA.Art.build = build

if __name__ == "__main__":
    GA.write()
    subprocess.run(["stylua", str(GA.ART_OUT.parent)], check=False)
