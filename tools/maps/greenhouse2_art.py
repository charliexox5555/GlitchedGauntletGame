#!/usr/bin/env python3
"""Greenhouse2 art pass (vault/01 Design/Maps/Greenhouse2.md): Greenhouse's placements (tools/maps/greenhouse_art.py,
on the kept layout) under the new map id and origin, with the Greenhouse2 kit, plus Greenhouse2's own decor.

    python tools/maps/greenhouse2_art.py    writes tools/studio/maps/Greenhouse2/Art.luau

The Greenhouse files are never written: this module patches greenhouse_art's output paths and template in memory.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import greenhouse_art as GA  # noqa: E402

ROOT = HERE.parents[1]
GA.ART_OUT = ROOT / "tools/studio/maps/Greenhouse2/Art.luau"
GA.PLAN_OUT = ROOT / "art-source/maps/Greenhouse2/plan.json"
GA.EXPORTS = ROOT / "art-source/maps/Greenhouse2/Exports"

GA.ART_TEMPLATE = (
    GA.ART_TEMPLATE.replace('newMap("Greenhouse", CFrame.new(1500, 200, -1500))', 'newMap("Greenhouse2", CFrame.new(0, 200, 3000))')
    .replace("-- Greenhouse art pass: GENERATED by tools/maps/greenhouse_layout.py --write (placements in tools/maps/greenhouse_art.py).",
             "-- Greenhouse2 art pass: GENERATED by tools/maps/greenhouse2_art.py (Greenhouse's placements on the kept layout,\n-- the Greenhouse2 kit, and Greenhouse2's own decor).")
    .replace("kit_bundle.py Greenhouse Structure -o gh_kit1.luau", "kit_bundle.py Greenhouse2 Structure -o gh2_kit1.luau")
    .replace("kit_bundle.py Greenhouse Garden -o gh_kit2.luau", "kit_bundle.py Greenhouse2 Garden -o gh2_kit2.luau")
    .replace("bundle.py Greenhouse Greybox Art Lighting -o greenhouse.luau", "bundle.py Greenhouse2 Greybox Art Lighting -o greenhouse2.luau")
    .replace('"Greenhouse art: %%d of %%d pieces placed', '"Greenhouse2 art: %%d of %%d pieces placed')
)

_build = GA.Art.build


def build(self):
    _build(self)
    # Greenhouse2 decor (concept 02-hero): banded flower tubs by the Dome's doors and the Fern House beds, at walls
    # and bed ends, never in a lane (no collision). Team B's half; both() adds A's turned copy.
    for x, z in DECOR_TUBS:
        self.both("Garden", "FlowerTub", x, 0, z, 0)
    # r2: slate roofs on the brick ranges (the ceilings' tops; the Sheds' blocks are (48 x 40 at 50, 62) and
    # (32 x 18 at 58, 91) in B's half, the Lodge 52 x 16 at (0, 110), the Orangery 80 x 16 at (0, 92) top 21).
    self.both("Roofs", "RoofShed48x40", 50, 15.0, 62, 0)
    self.both("Roofs", "RoofShed32x18", 58, 15.15, 91, 0)  # 0.15 over the 48x40 roof where their eaves overlap (z-fight)
    self.both("Roofs", "RoofLodge52x16", 0, 15.0, 110, 0)
    self.both("Roofs", "RoofOrangery80x16", 0, 21.0, 92, 0)
    # r2: the parkland round the walls (outside the 152 x 240 footprint): a ring of trees, B's half
    for i, (x, z) in enumerate(TREES):
        self.both("Park", "GardenTreeA" if i % 2 else "GardenTreeB", x, 0, z, (i * 90) % 360)  # right angles (the offline check boxes them)
    for x0, x1, z0, z1 in LAWNS:
        self.parts.append(("Park", "Lawn", x0, x1, -0.6, -0.05, z0, z1, "lawn"))
    return self


TREES = [(-100, 20), (-104, 52), (-96, 86), (-100, 118), (-70, 140), (-36, 146), (6, 148), (44, 142), (82, 132), (104, 100), (100, 66), (106, 34), (96, 6)]
# a lawn round the building, under its edges (top -0.05, below every floor); both() is not used for Parts, so both halves
LAWNS = [(-200, 200, 120.5, 260), (-200, 200, -260, -120.5), (76.5, 200, -120.5, 120.5), (-200, -76.5, -120.5, 120.5)]


# map space (x, z), B half; measured clear of the collision on the layout plan
DECOR_TUBS: list[tuple[float, float]] = [
    (12.2, 38.0), (-0.2, 38.0),  # inside the Dome's north door, either side
    (38.0, 30.2), (38.0, 17.8),  # inside the Dome's east door
    (-22.0, 76.2), (-22.0, 63.8),  # Fern House, at its west door
    (22.0, 60.2), (22.0, 47.8),  # Fern House, at its east door
    # kit v2: the Orangery dressed as the concept's spawn hall: tubs either side of its doors (the spawn view)
    (-1.8, 86.0), (-14.2, 86.0), (-25.8, 86.0), (-38.2, 86.0),
    (-15.8, 98.0), (-28.2, 98.0), (15.8, 98.0), (28.2, 98.0),
]  # from a clearance search on the layout blocks (1.5 radius, 3.0 off the wall plane, no solid below 4)

GA.Art.build = build
# v2 r3: the wall glass reflects the sky (Reflectance on SmoothPlastic; it stays opaque, so no see-through walls):
# every round's reviewers read the opaque frost as a flat painted wall
GA.ART_TEMPLATE = GA.ART_TEMPLATE.replace(
    '''				elseif string.sub(d.Name, -6) == "_Glass" or string.sub(d.Name, -6) == "_Water" then''',
    '''				elseif string.sub(d.Name, -6) == "_Frost" then
					d.Reflectance = 0.32
					d.CastShadow = false
				elseif string.sub(d.Name, -6) == "_Glass" or string.sub(d.Name, -6) == "_Water" then''')
# r3: the end tones from the palette table (B slate-blue, A terracotta); Greenhouse's saturated blue / yellow read
# as a stray bright table at the spawn
GA.L.ACCENT = dict(GA.L.ACCENT, A="#A8735A", B="#6F8DA6")  # kit v2 r2: muted (the blue table read saturated)
# r2: the Sheds and Lodge ceilings are flat roofs too; under the new slate roofs their tops read as slate, and
# inside a dark slate ceiling over the shaded lane (the Map Quality Standard's "Sheds: the one shaded lane").
GA.LOOKS = dict(GA.LOOKS, lodge_ceiling=("Slate", "6F7A86"), shed_ceiling=("Slate", "6F7A86"), dome_floor=("Pavement", "CDC4B2"))  # r3: the Dome floor in the halls' paving (limestone read as bare sand)

if __name__ == "__main__":
    GA.write()
    subprocess.run(["stylua", str(GA.ART_OUT.parent)], check=False)
