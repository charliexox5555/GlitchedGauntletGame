#!/usr/bin/env python3
"""Greenhouse2 layout (vault/01 Design/Maps/Greenhouse2.md; Map Quality Standard §2 step 2 and §7).

The layout is KEPT from Greenhouse: the same solids, spawns, barriers and checks (tools/maps/greenhouse_layout.py,
playtested and measured). Greenhouse2 is a new map id at a new world origin, so this wrapper writes the same greybox
under the new id and origin, and leaves every Greenhouse file untouched.

    python tools/maps/greenhouse2_layout.py            checks (the Greenhouse report) and the SVG
    python tools/maps/greenhouse2_layout.py --write    ...and writes tools/studio/maps/Greenhouse2/Greybox.luau
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import greenhouse_layout as G  # noqa: E402

ROOT = HERE.parents[1]
MAP = "Greenhouse2"
ORIGIN = (0, 200, 3000)  # free: checked in the match place 2026-11-06 (0 parts in 320 x 300 x 440 round it)
LUAU_OUT = ROOT / "tools/studio/maps/Greenhouse2/Greybox.luau"
SVG_OUT = ROOT / "vault/02 Art/References/maps/greenhouse2/greenhouse2-layout.svg"


def greybox_luau() -> str:
    src = G.greybox_luau()
    old = 'newMap("Greenhouse", CFrame.new(1500, 200, -1500))'
    assert src.count(old) == 1, "Greenhouse greybox header changed"
    src = src.replace(old, f'newMap("{MAP}", CFrame.new({ORIGIN[0]}, {ORIGIN[1]}, {ORIGIN[2]}))')
    src = src.replace(
        "-- Greenhouse greybox: GENERATED by tools/maps/greenhouse_layout.py --write.",
        "-- Greenhouse2 greybox: GENERATED by tools/maps/greenhouse2_layout.py --write (the Greenhouse layout, kept;\n"
        "-- new map id and origin). Edit the layout in tools/maps/greenhouse_layout.py.",
    )
    src = src.replace("bundle.py Greenhouse Greybox -o greenhouse_greybox.luau", "bundle.py Greenhouse2 Greybox -o greenhouse2_greybox.luau")
    src = src.replace('"Greenhouse greybox: %d parts', '"Greenhouse2 greybox: %d parts')
    return src


if __name__ == "__main__":
    res = G.report()
    SVG_OUT.parent.mkdir(parents=True, exist_ok=True)
    SVG_OUT.write_text(G.svg(res).replace(">Greenhouse<", ">Greenhouse2<"), encoding="utf-8")
    print(f"\nWrote {SVG_OUT}")
    if "--write" in sys.argv:
        LUAU_OUT.parent.mkdir(parents=True, exist_ok=True)
        LUAU_OUT.write_text(greybox_luau(), encoding="utf-8")
        print(f"Wrote {LUAU_OUT}")
        subprocess.run(["stylua", str(LUAU_OUT.parent)], check=False)
