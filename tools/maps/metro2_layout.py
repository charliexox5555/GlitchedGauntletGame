"""Metro2 layout: Metro's checked layout (tools/maps/metro_layout.py), unchanged, at Metro2's origin.

    python tools/maps/metro2_layout.py [--luau]

Map Quality Standard step 2 ("layout kept from the map note"): re-runs every Metro check (spawn safety,
route times, gaps, sightlines, perch share) on the same numbers, writes the layout SVG for Metro2 and,
with --luau, tools/studio/maps/Metro2/Greybox.luau at origin (3000, 200, 1500). After this the collision
boxes don't move (vault/01 Design/Maps/Metro2.md). Metro's own files are never written.
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import metro_layout as L  # noqa: E402

ROOT = HERE.parents[1]
LUAU_OUT = ROOT / "tools" / "studio" / "maps" / "Metro2" / "Greybox.luau"
SVG_OUT = ROOT / "vault" / "02 Art" / "References" / "maps" / "metro2" / "metro2-layout.svg"


def luau() -> str:
	src = L.luau()
	swaps = [
		('newMap("Metro", CFrame.new(1500, 200, 0))', 'newMap("Metro2", CFrame.new(3000, 200, 1500))'),
		("-- Metro greybox: GENERATED by tools/maps/metro_layout.py --luau.", "-- Metro2 greybox: GENERATED by tools/maps/metro2_layout.py --luau (Metro's layout)."),
		("bundle.py Metro Greybox -o metro_greybox.luau", "bundle.py Metro2 Greybox -o metro2_greybox.luau"),
		('"Metro greybox: %d parts', '"Metro2 greybox: %d parts'),
	]
	for a, b in swaps:
		assert src.count(a) == 1, a
		src = src.replace(a, b)
	return src


if __name__ == "__main__":
	res = L.report()
	SVG_OUT.parent.mkdir(parents=True, exist_ok=True)
	SVG_OUT.write_text(L.svg(res), encoding="utf-8")
	print(f"\nWrote {SVG_OUT}")
	if "--luau" in sys.argv:
		LUAU_OUT.parent.mkdir(parents=True, exist_ok=True)
		LUAU_OUT.write_text(luau(), encoding="utf-8")
		print(f"Wrote {LUAU_OUT}")
