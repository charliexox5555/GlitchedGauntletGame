def lua(v):
	if isinstance(v, bool):
		return "true" if v else "false"
	if isinstance(v, tuple):
		return "Color3.fromRGB(%d, %d, %d)" % v
	if isinstance(v, str):
		return '"%s"' % v
	return repr(v)


def style_block():
	out = ["-- BEGIN STYLE (generated by tools/maps/metro2_style.py --luau; edit the values there)", "-- stylua: ignore start",
		   "local ROLE: { [string]: { color: string, material: string, variant: string } } = {"]
	for k, (c, m, v) in ROLE.items():
		out.append('\t%s = { color = "%s", material = "%s", variant = "%s" },' % (k, c, m, v))
	out.append("}")
	out.append("local END_COLOUR = { B = \"%s\", A = \"%s\", Mid = \"%s\" }" % (END["B"], END["A"], END["Mid"]))
	out.append("local GLOW = { %s }" % ", ".join('%s = "%s"' % kv for kv in GLOW.items()))
	out.append("local VARIANTS: { [string]: { any } } = {")
	for k, (b, s, c, n) in VARIANTS.items():
		out.append('\t%s = { "%s", %d, "%s", "%s" },' % (k, b, s, c, n))
	out.append("}")
	out += ["-- stylua: ignore end", "-- END STYLE"]
	return "\n".join(out)


def light_block():
	out = ["-- BEGIN LIGHT (generated by tools/maps/metro2_style.py --luau; edit the values there)", "-- stylua: ignore start",
		   "local PROPS: { [string]: any } = {"]
	for k, v in LIGHTING.items():
		out.append("\t%s = %s," % (k, lua(v)))
	out.append("}")
	out.append("local FX: { [string]: { [string]: any } } = {")
	for k, d in FX.items():
		out.append("\t%s = { %s }," % (k, ", ".join("%s = %s" % (a, lua(b)) for a, b in d.items())))
	out.append("}")
	out += ["-- stylua: ignore end", "-- END LIGHT"]
	return "\n".join(out)


def splice(path, tag, block):
	s = path.read_text(encoding="utf-8")
	pat = re.compile(r"-- BEGIN %s.*?-- END %s" % (tag, tag), re.S)
	assert pat.search(s), "no %s block in %s" % (tag, path)
	path.write_text(pat.sub(lambda m: block, s), encoding="utf-8")
	print("wrote", tag, "->", path)


