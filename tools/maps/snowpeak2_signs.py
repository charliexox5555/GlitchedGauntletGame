#!/usr/bin/env python3
"""Snowpeak2 sign art: the lodge, station and patrol names rendered from a real font (Map Quality Standard -> Text).

    python tools/maps/snowpeak2_signs.py [--upload]

Cream Bahnschrift on transparent, sized to the kit's sign boards (Art.luau's sign() boards): lodge gables 13.4 x 2.2,
station boards 15.4 x 2.1, patrol huts 8.6 x 0.7. --upload sends them as Decals (art-source/maps/Snowpeak2/signs.json);
the install resolves image ids into "image" and `--luau` writes the SIGNS block of tools/studio/maps/Snowpeak2/Art.luau.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw

import bunker2_signs as B

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "art-source/maps/Snowpeak2/signs"
RECORD = ROOT / "art-source/maps/Snowpeak2/signs.json"
INK = (244, 236, 220, 255)
SIGNS = {
    "SNOWPEAK LODGE": (13.4, 2.2),
    "GONDOLA · NORTH PEAK": (15.4, 2.1),
    "GONDOLA · SOUTH PEAK": (15.4, 2.1),
    "SKI PATROL": (8.6, 0.7),
}


def render(text: str, w_st: float, h_st: float) -> Image.Image:
    w = 1024
    h = max(48, int(round(w * h_st / w_st)))
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    f, tw, gap = B.fit(d, text, int(w * 0.86), int(h * 0.62), spacing=0.12)
    B.spaced(d, text, w / 2, h / 2, f, tw, gap, INK)
    return im


def slug(t: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", t.upper()).strip("_")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    rec = json.loads(RECORD.read_text(encoding="utf-8")) if RECORD.exists() else {}
    for text, (w, h) in SIGNS.items():
        path = OUT / f"{slug(text)}.png"
        render(text, w, h).save(path)
        if "--upload" in sys.argv and not rec.get(text, {}).get("decal"):
            out = subprocess.run([sys.executable, str(ROOT / "tools/opencloud/upload_asset.py"), "--group", "11116787", "--type", "Decal",
                                  str(path), f"GG Snow2 Sign {slug(text)}"], capture_output=True, text=True)
            ids = [t for t in out.stdout.split() if t.isdigit()]
            rec[text] = {"file": str(path.relative_to(ROOT)).replace("\\", "/"), "decal": ids[-1] if ids else "", "image": ""}
            print(text, rec[text]["decal"])
    RECORD.write_text(json.dumps(rec, indent=1, ensure_ascii=False), encoding="utf-8")
    if "--luau" in sys.argv:
        p = ROOT / "tools/studio/maps/Snowpeak2/Art.luau"
        body = "local SIGN: { [string]: string } = {\n" + "\n".join(f'\t["{k}"] = "{v.get("image", "")}",' for k, v in rec.items()) + "\n}"
        s = p.read_text(encoding="utf-8")
        s, n = re.subn(r"-- BEGIN SIGNS.*?-- END SIGNS", lambda m: "-- BEGIN SIGNS (generated by tools/maps/snowpeak2_signs.py --luau; image ids)\n" + body + "\n-- END SIGNS", s, flags=re.S)
        assert n == 1
        p.write_text(s, encoding="utf-8", newline="\n")
        print("wrote SIGNS block")
