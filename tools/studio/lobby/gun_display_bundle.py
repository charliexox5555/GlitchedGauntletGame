"""Write the Studio script that builds the Lobby's display guns (Weapons wing) from the real game guns.

    python tools/studio/lobby/gun_display_bundle.py [-o out.luau] [--only Display_Phantom,Hero_Vandal,...]

For each display in DISPLAYS it reads the gun's build data (tools/studio/rojo/BuildData/<Id>.json: parts with their
centre, look, pbr flag, the asset id and the baked SurfaceAppearance set) and its profile
(art-source/lobby/Exports/GunProfiles.json, made by `build_lobby_kit_weapons.py -- --gun-profiles ...`: the gun's
underside along its length). The generated script loads the latest version of each gun's upload, scales every
MeshPart (Size and offset) by the display factor and assembles one anchored, non-colliding Model per display in
ServerStorage.LobbyKit (KitGroup "GunDisplay"), the way WeaponBuilder.luau assembles the game guns (mesh axes "Y").

Model space = Roblox gun space (muzzle -Z, up +Y, gun-left -X); the pivot is the centre of the gun's bounding box,
so `model:PivotTo(CFrame.fromMatrix(pos, muzzle:Cross(up), up))` shows the gun's right side when the muzzle points to
the viewer's right. Attributes: Length, Height, Scale, GunId, Low (the lowest point below the pivot) and
UnderProfile ("a0;da;u0,u1,..."): the underside height below the pivot sampled along the muzzle axis (a from the
pivot toward the muzzle), so the Art script can stand rods and pylons exactly under the gun.
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
BUILD = ROOT / "tools" / "studio" / "rojo" / "BuildData"
PROFILES = ROOT / "art-source" / "lobby" / "Exports" / "GunProfiles.json"

# (role, gun id, target length in studs) for Display/Hero; (role, id, scale) for Trophy.
DISPLAYS = [
	("Hero", "Vandal", 28.0),
	("Display", "Phantom", 15.5),
	("Display", "Guardian", 17.0),
	("Display", "Spectre", 13.5),
	("Display", "Judge", 15.0),
	("Display", "Operator", 18.0),
	("Display", "Odin", 18.0),
	("Display", "Classic", 8.5),
	("Display", "Sheriff", 8.5),
]
TROPHY_SCALE = 1.5
STEP = 3  # profile samples kept (every 0.06 studs of the real gun)
TROPHIES = ["Vandal", "Bulldog", "Stinger", "Bucky", "Marshal", "Outlaw", "Ares", "Ghost", "Shorty", "Knife"]

TEMPLATE = """--!strict
-- Generated by tools/studio/lobby/gun_display_bundle.py: builds the Lobby display guns (KitGroup GunDisplay).
local InsertService = game:GetService("InsertService")
local ServerStorage = game:GetService("ServerStorage")
assert(game.PlaceId == 133387545285290, "Lobby guns: this is not the Lobby place")

type Look = { material: string, color: string }
type PartData = { name: string, look: Look?, pbr: boolean, center: { number } }
type Surface = { ColorMap: number, NormalMap: number, RoughnessMap: number, MetalnessMap: number }
type Display = {
	name: string,
	gun: string,
	asset: number,
	scale: number,
	center: { number },
	size: { number },
	low: number,
	profile: string,
	surface: Surface?,
	parts: { PartData },
}

local DISPLAYS: { Display } = %(displays)s

local function G(x: number, y: number, z: number): Vector3
	return Vector3.new(-y, z, -x)
end
-- WeaponBuilder mesh axes "Y".
local ROT = CFrame.fromMatrix(Vector3.zero, G(-1, 0, 0), G(0, 1, 0), G(0, 0, -1))

local lib = ServerStorage:FindFirstChild("LobbyKit")
if not lib then
	lib = Instance.new("Folder")
	lib.Name = "LobbyKit"
	lib.Parent = ServerStorage
end
assert(lib)

local raws: { [number]: Instance } = {}
local function rawFor(asset: number): Instance
	local r = raws[asset]
	if not r then
		local version = InsertService:GetLatestAssetVersionAsync(asset)
		r = InsertService:LoadAssetVersion(version)
		raws[asset] = r
	end
	return r :: Instance
end

local report = {}
for _, d in DISPLAYS do
	local old = lib:FindFirstChild(d.name)
	if old then
		old:Destroy()
	end
	local meshes: { [string]: MeshPart } = {}
	for _, m in rawFor(d.asset):GetDescendants() do
		if m:IsA("MeshPart") then
			meshes[m.Name] = m
		end
	end
	local k = d.scale
	local c = G(d.center[1], d.center[2], d.center[3]) * k
	local model = Instance.new("Model")
	model.Name = d.name
	model:SetAttribute("KitGroup", "GunDisplay")
	model:SetAttribute("GunId", d.gun)
	model:SetAttribute("Scale", k)
	model:SetAttribute("Length", d.size[1] * k)
	model:SetAttribute("Height", d.size[3] * k)
	model:SetAttribute("Low", d.low * k)
	model:SetAttribute("UnderProfile", d.profile)
	local missing = {}
	local count = 0
	for _, p in d.parts do
		local src = meshes[p.name]
		if not src then
			table.insert(missing, p.name)
			continue
		end
		local part = src:Clone()
		part:ClearAllChildren()
		part.Size = src.Size * k
		part.CFrame = CFrame.new(G(p.center[1], p.center[2], p.center[3]) * k - c) * ROT
		part.Anchored = true
		part.CanCollide = false
		part.CanQuery = false
		part.CanTouch = false
		part.CastShadow = false
		part.Massless = true
		local look = p.look
		if look then
			part.Material = (Enum.Material :: any)[look.material]
			part.Color = Color3.fromHex(look.color)
			if look.color == "FF3DCB" and string.find(p.name, "Lens") then
				part.Transparency = 0.25
			end
		end
		local s = d.surface
		if p.pbr and s then
			local sa = Instance.new("SurfaceAppearance")
			sa.ColorMap = "rbxassetid://" .. s.ColorMap
			sa.NormalMap = "rbxassetid://" .. s.NormalMap
			sa.RoughnessMap = "rbxassetid://" .. s.RoughnessMap
			sa.MetalnessMap = "rbxassetid://" .. s.MetalnessMap
			sa.Parent = part
		end
		pcall(function()
			part.CollisionFidelity = Enum.CollisionFidelity.Box
		end)
		part.Parent = model
		count += 1
	end
	model.WorldPivot = CFrame.identity
	model.ModelStreamingMode = Enum.ModelStreamingMode.Atomic
	model.Parent = lib
	table.insert(report, string.format("%%s %%d parts%%s", d.name, count, #missing > 0 and (" missing " .. table.concat(missing, ",")) or ""))
end
for _, r in raws do
	r:Destroy()
end
local line = "GunDisplay: " .. table.concat(report, "; ")
print(line)
return line
"""


def luau(v):
	if isinstance(v, bool):
		return "true" if v else "false"
	if v is None:
		return "nil"
	if isinstance(v, (int, float)):
		return repr(round(v, 5)) if isinstance(v, float) else str(v)
	if isinstance(v, str):
		return json.dumps(v)
	if isinstance(v, list):
		return "{ " + ", ".join(luau(x) for x in v) + " }"
	if isinstance(v, dict):
		return "{ " + ", ".join(f"{k} = {luau(x)}" for k, x in v.items() if x is not None) + " }"
	raise TypeError(v)


def display(role, gid, value, profiles):
	data = json.loads((BUILD / f"{gid}.json").read_text(encoding="utf-8"))
	prof = profiles[gid]
	lo, hi = prof["min"], prof["max"]
	center = [(lo[i] + hi[i]) / 2 for i in range(3)]
	size = [hi[i] - lo[i] for i in range(3)]
	scale = value / size[0] if role != "Trophy" else value
	visible = data.get("options_visible", {})
	parts = []
	for p in data["parts"]:
		if p.get("option") and not visible.get(p["option"]):
			continue
		parts.append({"name": p["name"], "look": p.get("look"), "pbr": bool(p.get("pbr")), "center": p["center"]})
	# Underside along the muzzle axis, relative to the pivot (scaled): a = (x - cx) * k, u = (z - cz) * k.
	us = []
	for u in prof["under"][::STEP]:
		us.append("" if u is None else "%.2f" % ((u - center[2]) * scale))
	a0 = (prof["x0"] - center[0]) * scale
	da = prof["dx"] * STEP * scale
	profile = "%.4f;%.4f;%s" % (a0, da, ",".join(us))
	return {
		"name": f"{role}_{gid}",
		"gun": gid,
		"asset": data["assetId"],
		"scale": round(scale, 5),
		"center": [round(v, 5) for v in center],
		"size": [round(v, 5) for v in size],
		"low": round(lo[2] - center[2], 5),
		"profile": profile,
		"surface": {k: data["surface"][k] for k in ("ColorMap", "NormalMap", "RoughnessMap", "MetalnessMap")} if data.get("surface") else None,
		"parts": parts,
	}


def main():
	ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	ap.add_argument("-o", "--out")
	ap.add_argument("--only", help="comma-separated display names (Display_Phantom, Hero_Vandal, Trophy_Ghost, ...)")
	args = ap.parse_args()
	profiles = json.loads(PROFILES.read_text(encoding="utf-8"))
	items = list(DISPLAYS) + [("Trophy", g, TROPHY_SCALE) for g in TROPHIES]
	only = set(args.only.split(",")) if args.only else None
	out = []
	for role, gid, v in items:
		if only and f"{role}_{gid}" not in only:
			continue
		out.append(display(role, gid, v, profiles))
	body = "{\n" + "".join(f"\t{luau(d)},\n" for d in out) + "}"
	text = TEMPLATE % {"displays": body}
	if args.out:
		pathlib.Path(args.out).write_text(text, encoding="utf-8")
	else:
		sys.stdout.write(text)


if __name__ == "__main__":
	main()
