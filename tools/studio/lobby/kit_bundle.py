"""Write the Studio script that installs one Lobby kit group into the Lobby place.

    python tools/studio/lobby/kit_bundle.py Hub [-o out.luau]

Reads art-source/lobby/Exports/<Group>.json (tools/blender/export_lobby_kit.py) and
the asset id from Exports/assets.json (tools/opencloud/upload_models.py --lobby).
The script loads the upload, builds one Model per kit piece in ServerStorage.LobbyKit
(pivot = the Blender piece origin, so `kit:PivotTo(cf)` places it like the greybox)
and replaces that group's old pieces. Run it in the Lobby place only (Command Bar or
the Studio MCP); ArtKit.luau then clones the pieces into Workspace.Lobby.Art.

Axes (checked 2026-10-29 with the AxisTest upload): the importer lays an FBX vertex
at Blender (x, y, z) as mesh-local (-x, z, y), so each part gets a 180 degree turn
about Y to land on the lobby convention Roblox = (x, z, -y).
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
EXPORTS = ROOT / "art-source" / "lobby" / "Exports"

TEMPLATE = """--!strict
-- Generated by tools/studio/lobby/kit_bundle.py: installs kit group %(group)s.
local InsertService = game:GetService("InsertService")
local ServerStorage = game:GetService("ServerStorage")
assert(game.PlaceId == 133387545285290, "Lobby kit: this is not the Lobby place")

type Look = { material: string, color: string, variant: string?, transparency: number?, reflectance: number? }
type PartData = { piece: string, name: string, look: Look?, glow: boolean, center: { number }, size: { number } }

local GROUP = %(group_q)s
local ASSET_ID = %(asset)d
local PARTS: { PartData } = %(parts)s

local ROT = CFrame.Angles(0, math.pi, 0)
local function G(v: { number }): Vector3
	return Vector3.new(v[1], v[3], -v[2])
end

local lib = ServerStorage:FindFirstChild("LobbyKit")
if not lib then
	lib = Instance.new("Folder")
	lib.Name = "LobbyKit"
	lib.Parent = ServerStorage
end
assert(lib)
for _, old in lib:GetChildren() do
	if old:GetAttribute("KitGroup") == GROUP then
		old:Destroy()
	end
end

local raw = InsertService:LoadAsset(ASSET_ID)
local meshes: { [string]: MeshPart } = {}
for _, d in raw:GetDescendants() do
	if d:IsA("MeshPart") then
		meshes[d.Name] = d
	end
end

local models: { [string]: Model } = {}
local missing = {}
for _, p in PARTS do
	local src = meshes[p.name]
	if not src then
		table.insert(missing, p.name)
		continue
	end
	local model = models[p.piece]
	if not model then
		local m = Instance.new("Model")
		m.Name = p.piece
		m:SetAttribute("KitGroup", GROUP)
		m.WorldPivot = CFrame.identity
		m.Parent = lib
		models[p.piece] = m
		model = m
	end
	local part = src:Clone()
	part:ClearAllChildren()
	part.Name = p.name
	part.Anchored = true
	part.CanCollide = false
	part.CanQuery = false
	part.CanTouch = false
	part.CFrame = CFrame.new(G(p.center)) * ROT
	local look = p.look
	if look then
		part.Material = (Enum.Material :: any)[look.material]
		part.Color = Color3.fromHex(look.color)
		part.MaterialVariant = look.variant or ""
		part.Transparency = look.transparency or 0
		part.Reflectance = look.reflectance or 0
	end
	local big = math.max(p.size[1], p.size[2], p.size[3])
	if p.glow then
		part.Material = Enum.Material.Neon
		part:SetAttribute("Glow", true)
	end
	-- Shadows only from wall-sized pieces (Lobby Kit budgets).
	part.CastShadow = not p.glow and big >= 8 and part.Transparency < 0.5
	pcall(function()
		part.CollisionFidelity = Enum.CollisionFidelity.Box
	end)
	part.Parent = model
end
raw:Destroy()

local n = 0
for _ in models do
	n += 1
end
local line = string.format("kit %%s: %%d pieces, %%d parts, missing %%d %%s", GROUP, n, #PARTS - #missing, #missing, table.concat(missing, ","))
print(line)
return line
"""


def luau(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "nil"
    if isinstance(v, (int, float)):
        return repr(round(v, 5)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{ " + ", ".join(luau(x) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {luau(x)}" for k, x in v.items() if x is not None) + " }"
    raise TypeError(v)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("group")
    ap.add_argument("-o", "--out")
    args = ap.parse_args()
    data = json.loads((EXPORTS / f"{args.group}.json").read_text(encoding="utf-8"))
    assets = json.loads((EXPORTS / "assets.json").read_text(encoding="utf-8"))
    asset = assets[args.group]["assetId"]
    parts = [
        {k: p[k] for k in ("piece", "name", "look", "glow", "center", "size")}
        for p in data["parts"]
    ]
    body = "{\n" + "".join(f"\t{luau(p)},\n" for p in parts) + "}"
    out = TEMPLATE % {"group": args.group, "group_q": json.dumps(args.group), "asset": asset, "parts": body}
    if args.out:
        pathlib.Path(args.out).write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)


if __name__ == "__main__":
    main()
