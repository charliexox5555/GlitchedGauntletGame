"""Stage flat-skin installs for Studio through Rojo (round two, 2026-11-14).

    python tools/studio/make_flat_install_jobs.py <ids.json> [--version flat-d]
    python tools/studio/make_flat_install_jobs.py --clean

<ids.json> maps "Line/Item[/version]" to the uploaded FBX Model asset id.
Writes src/shared/_SkinInstall/Install.luau (a copy of
tools/studio/InstallFlatSkin.luau) and Jobs.luau (one job per item, from
each item's manifest_flat.json), which Rojo syncs into
ReplicatedStorage.Shared._SkinInstall. Run in Studio (Edit, command bar or
MCP):

    local f = game.ReplicatedStorage.Shared._SkinInstall
    local install, jobs = require(f.Install:Clone()), require(f.Jobs:Clone())
    for _, job in jobs do print(job.line, job.gun, pcall(install, job)) task.wait() end

then `--clean` to remove the staging folder (it is not part of the game).
"""
import json, os, shutil, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SKINS = os.path.join(ROOT, "art-source", "weapons", "Skins")
STAGE = os.path.join(ROOT, "src", "shared", "_SkinInstall")
TILES = {
    "Giltfold_Wave": (110202734035328, 0.36),   # v2 wave scales (v1 129212333437892)
    "Payload_Carbon": (113233933286545, 0.12),
    "Payload_Foil": (140526423579451, 0.5),     # v2 faceted foil (v1 103618884326351)
    "Sealwork_Ruby": (135106383206479, 0.4),
    "Moltframe_Flow": (96163927400875, 1.2),
}
LATEST = {"Moltframe/Vandal": "v05"}
KEPT = {  # Vandal installs keep the round-two stock finish on unreplaced parts
    "Giltfold": ("26252D", "SmoothPlastic"), "Sealwork": ("D2A04A", "Metal"), "Payload": ("20262E", "SmoothPlastic"),
    "Inkshift": ("1D2431", "SmoothPlastic"), "Moltframe": ("5A6170", "Metal"),
    "TempestStrike": ("1D2433", "SmoothPlastic"),
}


def lua(v, ind=""):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(round(v, 6)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {lua(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def newest(line, item):
    key = f"{line}/{item}"
    if key in LATEST:
        return LATEST[key]
    d = os.path.join(SKINS, line, item)
    vs = sorted(v for v in os.listdir(d) if v.startswith("v") and os.path.exists(os.path.join(d, v, "manifest_flat.json")))
    return vs[-1]


def job(key, asset_id, version):
    parts = key.split("/")
    line, item = parts[0], parts[1]
    ver = parts[2] if len(parts) > 2 else newest(line, item)
    m = json.load(open(os.path.join(SKINS, line, item, ver, "manifest_flat.json")))
    gun = m.get("gun", item)
    specs = {}
    used = set()
    for name, p in m["parts"].items():
        s = {"b": p["bone"], "c": p["center"], "s": p["size"], "col": p["color"], "mat": p["material"], "refl": p["reflectance"]}
        if p.get("pattern"):
            s["pat"] = p["pattern"]
            used.add(p["pattern"])
        specs[name] = s
    j = {"line": line, "gun": gun, "item": item, "version": version, "assetId": asset_id,
         "replaced": {p: True for p in m["replaced_stock_prefixes"]},
         "tiles": {t: {"id": TILES[t][0], "studs": TILES[t][1]} for t in sorted(used)}}
    if item == "Vandal":
        j["kept"] = list(KEPT[line])
    if m.get("joints"):
        j["joints"] = m["joints"]
    out = "\t{\n"
    for k, v in j.items():
        out += f"\t\t{k} = {lua(v)},\n"
    out += "\t\tparts = {\n" + "".join(f"\t\t\t{n} = {lua(s)},\n" for n, s in sorted(specs.items())) + "\t\t},\n\t},\n"
    return out


def main():
    if "--clean" in sys.argv:
        shutil.rmtree(STAGE, ignore_errors=True)
        print("removed", STAGE)
        return
    ids = json.load(open(sys.argv[1]))
    version = sys.argv[sys.argv.index("--version") + 1] if "--version" in sys.argv else "flat-d"
    os.makedirs(STAGE, exist_ok=True)
    shutil.copy(os.path.join(ROOT, "tools", "studio", "InstallFlatSkin.luau"), os.path.join(STAGE, "Install.luau"))
    body = "-- Generated by tools/studio/make_flat_install_jobs.py (temporary staging, not game code).\nreturn {\n"
    body += "".join(job(k, v, version) for k, v in ids.items())
    body += "}\n"
    open(os.path.join(STAGE, "Jobs.luau"), "w", newline="\n").write(body)
    print("staged", len(ids), "jobs ->", STAGE)


if __name__ == "__main__":
    main()
